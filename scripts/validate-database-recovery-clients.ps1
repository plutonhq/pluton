param(
    [string]$RuntimeImage = 'pluton-recovery-clients:local',
    [string]$DatabaseFixtureImage = 'pluton-recovery-db-only:local'
)
# Real final-image imports; no production endpoint input, host network, ports, credentials or data mounts.
$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$fixtureId = [Guid]::NewGuid().ToString('N')
$databaseContainer = "pluton-client-db-$fixtureId"
$controlVolume = "pluton-client-control-$fixtureId"
$databaseCreated = $false
$volumeCreated = $false
try {
    & docker run --rm --network none --read-only --user '10001:10001' --entrypoint node $RuntimeImage --loader ./backend/loader.mjs /usr/local/libexec/pluton/verify-database-recovery-clients.mjs
    if ($LASTEXITCODE -ne 0) { throw 'Final runtime image client verification failed.' }
    & docker volume create $controlVolume | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'Could not create private disposable fixture control volume.' }
    $volumeCreated = $true
    $serverScript = (Resolve-Path (Join-Path $repoRoot 'backend/__tests__/integration/databaseRecoveryClients.server.mjs')).Path
    $serverArguments = @('run','--detach','--init','--name',$databaseContainer,'--network','none','--read-only','--user','1000:10001',
        '--tmpfs','/tmp:rw,noexec,nosuid,nodev,uid=1000,gid=10001,mode=1777,size=512m',
        '--mount',"type=volume,source=$controlVolume,target=/fixture-control",
        '--mount',"type=bind,source=$serverScript,target=/fixture-server.mjs,readonly",$DatabaseFixtureImage)
    & docker @serverArguments | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'Could not start disposable database-only fixture.' }
    $databaseCreated = $true
    $ready = $false
    for ($attempt = 0; $attempt -lt 180; $attempt++) {
        & docker exec $databaseContainer test -f /fixture-control/ready 2>$null
        if ($LASTEXITCODE -eq 0) { $ready = $true; break }
        $running = & docker inspect --format '{{.State.Running}}' $databaseContainer
        if ($running -ne 'true') {
            # This fixed fixture emits only closed initialization stages, never credentials/SQL.
            & docker logs $databaseContainer
            throw 'Disposable database-only fixture stopped during initialization.'
        }
        Start-Sleep -Milliseconds 500
    }
    if (-not $ready) { throw 'Disposable database-only fixture was not ready.' }
    $clientScript = (Resolve-Path (Join-Path $repoRoot 'backend/__tests__/integration/databaseRecoveryClients.smoke.mjs')).Path
    $clientArguments = @('run','--rm','--init','--read-only','--user','10001:10001',
        '--network',"container:$databaseContainer", # fixture loopback only; no host/production network
        '--tmpfs','/tmp:rw,noexec,nosuid,nodev,uid=10001,gid=10001,mode=1777,size=128m',
        '--tmpfs','/data:rw,noexec,nosuid,nodev,uid=10001,gid=10001,mode=700,size=64m',
        '--mount',"type=volume,source=$controlVolume,target=/fixture-control,readonly",
        '--mount',"type=bind,source=$clientScript,target=/fixture-test.mjs,readonly",
        '--entrypoint','node',$RuntimeImage,'--loader','./backend/loader.mjs','/fixture-test.mjs')
    & docker @clientArguments
    if ($LASTEXITCODE -ne 0) { throw 'Final-image recovery import integration failed.' }
} finally {
    # Exact names generated by this invocation only. Never remove unrelated resources.
    if ($databaseContainer -notmatch '^pluton-client-db-[a-f0-9]{32}$' -or $controlVolume -notmatch '^pluton-client-control-[a-f0-9]{32}$') { throw 'Refusing unsafe disposable fixture cleanup.' }
    if ($databaseCreated) { & docker rm --force $databaseContainer | Out-Null }
    if ($volumeCreated) { & docker volume rm $controlVolume | Out-Null }
}
